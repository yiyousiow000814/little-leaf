'use strict';
const assert=require('node:assert/strict'), fs=require('node:fs'), path=require('node:path');
const crypto=require('node:crypto'), cp=require('node:child_process'), Module=require('node:module');
const arg=name=>{const i=process.argv.indexOf('--'+name);assert(i>=0&&process.argv[i+1],name+' required');return process.argv[i+1];};
const repo=path.resolve(arg('repo'));
assert.equal(arg('case'),'already_open_old');
assert.equal(cp.execFileSync('git',['rev-parse','HEAD'],{cwd:repo,encoding:'utf8'}).trim(),'d484fb22623039c7078a9cce1c06bc3084c9f146');
const original=path.join(repo,'tests/rendering/wall_compatibility_browser.js');
const bytes=fs.readFileSync(path.join(__dirname,'wall_compatibility_browser.diagnostic.js'));
const digest=data=>crypto.createHash('sha256').update(data).digest('hex');
assert.equal(digest(fs.readFileSync(original)),'190f10d024314e0a43415863ef1c9e901572a917763ef6a08bea9b4f3c748615');
assert.equal(digest(bytes),'8b58a370c5f01e20376f7f9d33a0f063d12a6390755f9d1b1634055657132540');
const nativeRequire=Module.createRequire(original), driver=process.env.PLAYWRIGHT_MODULE||'playwright';
assert.equal(nativeRequire(driver+'/package.json').version,'1.63.0');
assert.equal(process.env.PLAYWRIGHT_CHROMIUM_CHANNEL,'chrome');
const source=bytes.toString('utf8').replace('if (require.main === module) main().catch','main().catch');
const m=new Module(original,module);
m.filename=original; m.paths=Module._nodeModulePaths(path.dirname(original));
m._compile(source,original);
